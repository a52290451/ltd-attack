"""SOTA-v1 strict, streaming Historical DEV direction adapter (stdlib only).

This adapter changes NO samples or labels. It is model-agnostic and exposes
5000 signed packet directions, preserving original order, with zero right
padding / deterministic right truncation. It does not open Future-B / C or
fit normalization. The model's CNN tensor layout is a separate model decision.
"""
from __future__ import annotations

from array import array
import ast
from collections import Counter
import csv
import hashlib
import json
from pathlib import Path
import sys
from typing import Iterator, NamedTuple

DEV_SPLITS=("DEV_EARLY","DEV_MIDDLE","DEV_LATE")
FROZEN_COUNTS={"DEV_EARLY":19098,"DEV_MIDDLE":20160,"DEV_LATE":18658}
DEFAULT_LENGTH=5000

class DevExample(NamedTuple):
    pcap_uid:str
    site_label:str
    label_id:int
    date:str
    temporal_split:str
    directions:array
    original_length:int

def digest(path:Path)->str:
    h=hashlib.sha256()
    with Path(path).open("rb") as f:
        for chunk in iter(lambda:f.read(4*1024*1024),b""):
            h.update(chunk)
    return h.hexdigest()

def parse_direction(text:str)->array:
    """Strict signed traffic sequence: -1/0/+1; no invented values or interpolation."""
    if not isinstance(text,str) or not text.startswith("[") or not text.endswith("]"):
        raise ValueError("direction_vector is not a bracketed list")
    try:
        parsed=ast.literal_eval(text)
    except (ValueError,TypeError,MemoryError,SyntaxError,RecursionError) as exc:
        raise ValueError("direction_vector is not a valid list") from exc
    if not isinstance(parsed,(list,tuple)):
        raise ValueError("direction_vector must contain a list/tuple")
    if not parsed:
        raise ValueError("empty direction vector")
    result=array("b")
    for value in parsed:
        if type(value) not in (int,float) or value not in (-1,0,1):
            raise ValueError("direction_vector contains value other than -1,0,+1")
        result.append(int(value))
    return result

def fixed_length(values:array,length:int=DEFAULT_LENGTH)->array:
    if type(length) is not int or length<=0:
        raise ValueError("input length must be a positive integer")
    if not isinstance(values,array) or values.typecode!="b":
        raise TypeError("expected signed byte array('b')")
    out=values[:length]
    if len(out)<length:out.extend([0]*(length-len(out)))
    if len(out)!=length:raise AssertionError("direction length != expected length")
    return out

def load_s1_dev_index(manifest:Path):
    """Load only the UID/date/label index generated by S1; verify its SHA256."""
    info=json.loads(Path(manifest).read_text(encoding="utf-8"))
    if (info.get("classification")!="SOTA_S1_HISTORICAL_DEV_ONLY_FROZEN_INDEX"
        or info.get("uid_count")!=57916 or info.get("site_count")!=65
        or info.get("training_not_started") is not True
        or info.get("future_b_not_opened") is not True):
        raise ValueError("S1 provenance and 57916/65 population contract failed")
    idx=Path(info["dev_index_file"])
    order=Path(info["label_order_file"])
    if digest(idx)!=info["dev_index_sha256"] or digest(order)!=info["label_order_sha256"]:
        raise ValueError("S1 index/label file SHA256 mismatch")
    labels=json.loads(order.read_text(encoding="utf-8"))
    if len(labels)!=65 or len(set(labels))!=65:
        raise ValueError("S1 label order is not 65 unique labels")
    class_to_id={str(x):i for i,x in enumerate(labels)}
    by_uid={}
    counts=Counter()
    with idx.open(newline="",encoding="utf-8") as f:
        reader=csv.DictReader(f)
        if set(reader.fieldnames or []) != {
            "pcap_uid","site_label","capture_date","temporal_split"}:
            raise ValueError("S1 UID index columns are not canonical")
        for row in reader:
            uid=row["pcap_uid"]
            split=row["temporal_split"]
            if not uid or uid in by_uid or split not in DEV_SPLITS:
                raise ValueError("S1 UID duplicate or non-DEV split")
            if row["site_label"] not in class_to_id:
                raise ValueError("S1 class outside selected 65")
            by_uid[uid]=(row["site_label"],row["capture_date"],split)
            counts[split]+=1
    if len(by_uid)!=57916 or dict(counts)!=FROZEN_COUNTS:
        raise ValueError("S1 UID count or chronological split mismatch")
    return by_uid,class_to_id,info

def iter_dev_vectors(source:Path,by_uid:dict,class_to_id:dict,
                     length:int=DEFAULT_LENGTH,
                     required_splits:tuple[str,...]=DEV_SPLITS,
                     per_split_limit:int|None=None)->Iterator[DevExample]:
    """Stream DEV vectors only, skipping INTERNAL and noncanonical Historical rows.

    For a full pass the caller must independently assert the yielded UID count
    and exact set equality; for a smoke pass it can stop after bounded samples.
    Bounded sample mode skips parsing vectors once a split has enough samples.
    No model training/normalization or Future-B access occurs.
    """
    if not set(required_splits).issubset(DEV_SPLITS) or not required_splits:
        raise ValueError("invalid DEV-only split selection")
    if per_split_limit is not None and (
        type(per_split_limit) is not int or per_split_limit < 1):
        raise ValueError("per_split_limit must be a positive integer")
    selected=Counter()
    csv.field_size_limit(sys.maxsize)
    with Path(source).open(newline="",encoding="utf-8") as f:
        reader=csv.DictReader(f)
        if not {"pcap_uid","site_label","direction_vector"}.issubset(
                reader.fieldnames or []):
            raise ValueError("Historical vectors missing required columns")
        seen=set()
        for row in reader:
            uid=row["pcap_uid"]
            reference=by_uid.get(uid)
            if reference is None or reference[2] not in required_splits:continue
            if per_split_limit is not None and selected[reference[2]]>=per_split_limit:
                continue
            if uid in seen:raise ValueError("duplicate DEV vector UID")
            seen.add(uid)
            site,date,split=reference
            if row["site_label"]!=site:raise ValueError("Micro/Macro label differs by UID")
            raw=parse_direction(row["direction_vector"])
            item=DevExample(uid,site,class_to_id[site],date,split,
                            fixed_length(raw,length),len(raw))
            selected[split]+=1
            yield item
            if per_split_limit is not None and all(
                    selected[x]>=per_split_limit for x in required_splits):
                return
