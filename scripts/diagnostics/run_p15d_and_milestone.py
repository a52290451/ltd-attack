def verify_outputs(directory,manifest_name,names,stage):
    obj=json.loads((directory/manifest_name).read_text())
    if obj.get("stage")!=stage or set(obj.get("outputs_sha256",{}))!=set(names):
        raise RuntimeError("MANIFEST_STAGE_OR_OUTPUT_SET_INVALID: "+stage)
    if obj.get("future_b_opened") is not False or obj.get("training_allowed") is not False:
        # 15B uses no_training=true rather than training_allowed=false.
        if stage!="P15B_FROZEN_FUSION_ABLATION" or obj.get("future_b_opened") is not False or obj.get("no_training") is not True:
            raise RuntimeError("SCIENTIFIC_POLICY_MISMATCH: "+stage)
    for name,h in obj["outputs_sha256"].items():
        if sha(directory/name)!=h:raise RuntimeError("OUTPUT_SHA_MISMATCH: "+name)
    return obj

def batch_f1(cms):
    diag=np.diagonal(cms,axis1=1,axis2=2)
    denom=cms.sum(axis=1)+cms.sum(axis=2)
    per=np.divide(2*diag,denom,out=np.zeros_like(denom,dtype=np.float64),where=denom>0)
    return per.mean(axis=1)

def bootstrap_paired(y,dates,old,new,iterations,seed):
    unique,inv=np.unique(dates,return_inverse=True)
    if len(unique)<2:raise RuntimeError("INSUFFICIENT_DAY_BLOCKS")
    d=len(unique)
    cms=[];top5=[]
    for prob in (old,new):
        pred=prob.argmax(axis=1)
        rank=ranks(prob,y)
        cm=np.zeros((d,NCLASS,NCLASS),dtype=np.int64)
        t5=np.zeros(d,dtype=np.int64)
        for k in range(d):
            mask=inv==k
            cm[k]=np.bincount(NCLASS*y[mask]+pred[mask],minlength=NCLASS*NCLASS).reshape(NCLASS,NCLASS)
            t5[k]=int(np.sum(rank[mask]<=5))
        cms.append(cm)
        top5.append(t5)
    rng=np.random.default_rng(seed)
    weights=rng.multinomial(d,np.full(d,1/d),size=iterations)
    n=weights@cms[0].sum(axis=(1,2))
    if (n==0).any():raise RuntimeError("EMPTY_BOOTSTRAP")
    scores=[]
    for cm,t5 in zip(cms,top5):
        merged=(weights@cm.reshape(d,-1)).reshape(iterations,NCLASS,NCLASS)
        correct=np.diagonal(merged,axis1=1,axis2=2).sum(axis=1)
        scores.append((correct/n,batch_f1(merged),(weights@t5)/n))
    delta=np.stack([scores[1][i]-scores[0][i] for i in range(3)],axis=1)
    ret={"day_blocks":d}
    for i,name in enumerate(("accuracy","macro_f1","top5_accuracy")):
        ret[name+"_ci_low"]=float(np.quantile(delta[:,i],.025))
        ret[name+"_ci_high"]=float(np.quantile(delta[:,i],.975))
        ret[name+"_fraction_positive"]=float(np.mean(delta[:,i]>0))
    return ret

