#!/usr/bin/env python3
"""One-shot numerical trace identity audit, not a UID equality test.

Historical DEV+09B and Future-B are compared by entire canonical packet
direction sequence and relative float64 timestamp sequence rounded to 1 us.
The source datasets and class/UID memberships are verified against frozen
indexes; no model inputs or checkpoints are modified. It makes no claim about
near-duplicate traces generated by different recordings or acquisition systems.
"""
from __future__ import annotations
import argparse,csv,hashlib,json,os,sys,struct
from collections import Counter,defaultdict
from pathlib import Path
import numpy as np

def need(ok,why):
    if not ok:raise RuntimeError("SOTA_NUMERIC_IDENTITY_AUDIT_BLOCKED "+why)
def sha(path):
    h=hashlib.sha256()
    with Path(path).open("rb") as stream:
        for chunk in iter(lambda:stream.read(8*1024*1024),b""):
            h.update(chunk)
    return h.hexdigest()
def read_scores(path):
    with np.load(path,allow_pickle=False) as z:
        uid=z["pcap_uid"].astype(str)
        dates=z["query_date"].astype("datetime64[D]").astype(str)
        y=z["y_true"].astype(int)
        labs=z["candidate_labels"].astype(str)
    need(len(uid)==len(set(uid)),"duplicate frozen score UIDs")
    return {str(k):(str(labs[i]),str(dt)) for k,i,dt in zip(uid,y,dates)}
def fingerprint(directions,times):
    # Numeric rather than textual: sign bytes and relative microseconds.
    # Use the same precision in all groups; no sample IDs involved.
    n=len(directions)
    need(n>1 and len(times)==n,"direction/time mismatch")
    d=np.asarray(directions,dtype=np.int8)
    t=np.asarray(times,dtype=np.float64)
    need(np.isin(d,(-1,1)).all(),"invalid signs")
    need(np.isfinite(t).all(),"invalid timestamps")
    ts=np.rint((t-t[0])*1e6).astype("<i8")
    dbytes=d.tobytes()
    direction_hash=hashlib.sha256(struct.pack("<Q",n)+dbytes).hexdigest()
    full_hash=hashlib.sha256(struct.pack("<Q",n)+dbytes+ts.tobytes()).hexdigest()
    return direction_hash,full_hash
def main():
    p=argparse.ArgumentParser()
    p.add_argument("--repo",type=Path,required=True)
    p.add_argument("--base",type=Path,required=True)
    p.add_argument("--output",type=Path,required=True)
    args=p.parse_args()
    sys.path.insert(0,str(args.repo))
    from scripts.sota.sota_paths_v1 import S1,FUTURE,STORAGE
    from src.models.sota.v1.data_adapter import parse_direction
    from src.models.sota.v1.timing_adapter import parse_times
    s1=json.loads(S1.read_text())
    idx=Path(s1["dev_index_file"])
    need(sha(idx)==s1["dev_index_sha256"],"DEV index source SHA")
    with idx.open(newline="",encoding="utf-8") as stream:
        dev={}
        for row in csv.DictReader(stream):
            k=row["pcap_uid"]
            need(k not in dev,"duplicate DEV UID")
            dev[k]=(row["site_label"],row["capture_date"])
    need(len(dev)==57916,"DEV count")
    root=args.base/"artifacts/sota/s9_netclr_author_original_v1/evaluation"
    hist09=read_scores(root/"09B/scores_sota_aligned.npz")
    future=read_scores(root/"10B_DEV_FROZEN/scores_sota_aligned.npz")
    need(len(hist09)==14687 and len(future)==18543,"cohort counts")
    need(not (set(dev)&set(hist09)),"DEV/09B overlap within historical")
    hist_source=Path(s1["historical_checksums"]["historical_vectors"]["path"])
    future_source=STORAGE/"future/CLEAN_final_vectors_sites_concept_drift.csv"
    fm=json.loads(FUTURE.read_text())
    need(sha(hist_source)==s1["historical_checksums"]["historical_vectors"]["sha256"],
         "Historical source SHA mismatch")
    need(sha(future_source)==fm["future_inputs"]["micro"]["sha256"],
         "Future source SHA mismatch")
    cohorts={"DEV":dev,"09B":hist09,"Future-B":future}
    hist_dir=defaultdict(list);hist_full=defaultdict(list)
    counts=Counter()
    uid_hist_labels={}
    date_sets=defaultdict(set)
    seen=set()
    csv.field_size_limit(sys.maxsize)
    with hist_source.open(newline="",encoding="utf-8") as stream:
        rd=csv.DictReader(stream)
        need({"pcap_uid","site_label","direction_vector","time_vector"}<=set(rd.fieldnames or ()),
             "historical CSV format")
        for row in rd:
            uid=row["pcap_uid"]
            group="DEV" if uid in dev else "09B" if uid in hist09 else None
            if group is None:continue
            need(uid not in seen,"duplicate selected historical UID")
            seen.add(uid)
            meta=cohorts[group][uid]
            need(row["site_label"]==meta[0],group+" source label mismatch")
            hdir,hfull=fingerprint(parse_direction(row["direction_vector"]),
                                   parse_times(row["time_vector"]))
            hist_dir[hdir].append((group,uid))
            hist_full[hfull].append((group,uid))
            uid_hist_labels[uid]=meta[0]
            date_sets[group].add(meta[1])
            counts[group]+=1
    need(counts["DEV"]==57916 and counts["09B"]==14687,
         "incomplete historical source coverage")
    counts["Future-B"]=0
    seen_future=set()
    matched_dir=matched_full=0
    across_uid_dir=across_uid_full=0
    mismatched_label_full=0
    overlap_by_uid=Counter()
    overlap_label_equal=Counter()
    matched_full_by_group=Counter()
    matched_dir_by_group=Counter()
    examples=[]
    cross_same_label_direction=0
    cross_same_label_full=0
    with future_source.open(newline="",encoding="utf-8") as stream:
        rd=csv.DictReader(stream)
        need({"pcap_uid","site_label","direction_vector","time_vector"}<=set(rd.fieldnames or ()),
             "future CSV format")
        for row in rd:
            uid=row["pcap_uid"]
            if uid not in future:continue
            need(uid not in seen_future,"duplicate selected Future UID")
            seen_future.add(uid)
            site,date=future[uid]
            need(row["site_label"]==site,"Future source label mismatch")
            d,f=fingerprint(parse_direction(row["direction_vector"]),
                            parse_times(row["time_vector"]))
            groups={entry[0] for entry in hist_dir.get(d,())}
            fgroups={entry[0] for entry in hist_full.get(f,())}
            if groups:
                matched_dir+=1
                for group in groups:matched_dir_by_group[group]+=1
                if any(entry[1]!=uid for entry in hist_dir[d]):across_uid_dir+=1
                if any(uid_hist_labels[entry[1]]==site for entry in hist_dir[d]):
                    cross_same_label_direction+=1
            if fgroups:
                matched_full+=1
                for group in fgroups:matched_full_by_group[group]+=1
                if any(entry[1]!=uid for entry in hist_full[f]):across_uid_full+=1
                if any(uid_hist_labels[entry[1]]!=site for entry in hist_full[f]):
                    mismatched_label_full+=1
                if any(uid_hist_labels[entry[1]]==site for entry in hist_full[f]):
                    cross_same_label_full+=1
                if len(examples)<8:
                    examples.append({"future_uid_redacted_sha12":hashlib.sha256(uid.encode()).hexdigest()[:12],
                                     "groups":sorted(fgroups),"same_label":any(
                                        uid_hist_labels[x[1]]==site for x in hist_full[f])})
            if uid in dev:
                overlap_by_uid["DEV"]+=1
                overlap_label_equal["DEV"]+=int(site==dev[uid][0])
            if uid in hist09:
                overlap_by_uid["09B"]+=1
                overlap_label_equal["09B"]+=int(site==hist09[uid][0])
            date_sets["Future-B"].add(date)
            counts["Future-B"]+=1
    need(len(seen_future)==18543,"incomplete Future UID coverage")
    cross_date={
        "DEV_vs_FutureB_common_dates":len(date_sets["DEV"]&date_sets["Future-B"]),
        "09B_vs_FutureB_common_dates":len(date_sets["09B"]&date_sets["Future-B"])}
    out={
      "classification":"LTD_CANONICAL_NUMERIC_ALL_COHORT_TRACE_IDENTITY_V1",
      "numeric_fingerprint":"SHA256(packet_count, complete signed direction int8 vector, complete timestamp float64 vector minus first timestamp rounded to integer microseconds)",
      "data_source_sha_verified":True,
      "n":dict(counts),"uid_overlap_by_origin":dict(overlap_by_uid),
      "uid_overlap_same_label":dict(overlap_label_equal),
      "global_direction_only_exact_matches_future_to_historical":matched_dir,
      "global_direction_and_time_exact_matches_future_to_historical":matched_full,
      "matches_under_DIFFERENT_UID_direction":across_uid_dir,
      "matches_under_DIFFERENT_UID_direction_and_time":across_uid_full,
      "direction_matches_same_label":cross_same_label_direction,
      "full_matches_same_label":cross_same_label_full,
      "full_matches_different_label":mismatched_label_full,
      "direction_matches_by_historical_group":dict(matched_dir_by_group),
      "full_matches_by_historical_group":dict(matched_full_by_group),
      "capture_date_overlaps":cross_date,
      "redacted_full_matches_sample":examples,
      "interpretation":(
        "FAIL_EXACT_NUMERIC_CROSS_COHORT_INPUT_DUPLICATES_FOUND" if matched_full>0 else
        "PASS_NO_EXACT_NUMERIC_TRACE_DUPLICATES_UID_REUSE_DETECTED"),
      "limits":[
        "No exact numeric duplicates at microsecond resolution is NOT a proof that recordings cannot be near duplicates, derived from shared data, or re-captured under related conditions.",
        "Different UID values could still refer to related traces; global numerical equality is checked regardless of UID.",
        "UID reuse is detected; never rely on UID as a globally unique cross-campaign capture key.",
        "One microsecond tolerance can merge very close but not exactly identical timings; different acquisition units require independent metadata audit.",
        "This does not prove original-paper fidelity or independent retraining protocol."],
    }
    need(not args.output.exists(),"refuse overwrite "+str(args.output))
    args.output.parent.mkdir(parents=True,exist_ok=True)
    args.output.write_text(json.dumps(out,indent=2,ensure_ascii=False)+"\n")
    print("NUMERIC_IDENTITY_STATUS",out["interpretation"],flush=True)
    print("UID_REUSE",json.dumps(out["uid_overlap_by_origin"]),flush=True)
    print("GLOBAL_DIRECTION_EXACT_MATCHES",matched_dir,flush=True)
    print("GLOBAL_DIRECTION_AND_TIME_EXACT_MATCHES",matched_full,flush=True)
    print("CAPTURE_DATE_OVERLAPS",json.dumps(cross_date),flush=True)
    print("NUMERIC_IDENTITY_AUDIT_REPORT",args.output,flush=True)
if __name__=="__main__":main()
