def main():
    conf=yaml.safe_load(CONFIG.read_text())
    if conf["stage"]!="P15D_HIST_PAIRED_M0_M1" or conf["scientific_status"]["promotion_allowed"]:
        raise RuntimeError("INVALID_PROTOCOL")
    if not conf["scientific_status"]["historical_only"] or not conf["scientific_status"]["training_forbidden"]:
        raise RuntimeError("FORBIDDEN_DATA_POLICY")
    if OUT.exists():raise RuntimeError("P15D_OUTPUT_EXISTS_NO_OVERWRITE")
    a=verify_outputs(P15A,"P15A_manifest.json",
        ["P15A_mechanisms_summary.csv","P15A_day_counts.csv","P15A_site_counts.csv","P15A_day_block_bootstrap.csv"],
        "P15A_MECH")
    b=verify_outputs(P15B,"P15B_manifest.json",["P15B_summary.csv","P15B_bootstrap.csv"],
        "P15B_FROZEN_FUSION_ABLATION")
    c=verify_outputs(P15C,"P15C_manifest.json",
        ["P15C_components.csv","P15C_day_counts.csv","P15C_site_counts.csv"],
        "P15C_HIST_COMPONENTS")
    if sha(Path(__file__).resolve())=="":raise RuntimeError("SCRIPT_SHA_FAILURE")
    for path,digest in c.get("inputs_sha256",{}).items():
        p=Path(path)
        if not p.is_file() or sha(p)!=digest:raise RuntimeError("P15C_SOURCE_MISMATCH "+path)
    print("P15A_4 P15B_2 P15C_3_OUTPUT_HASHES_VERIFIED")
    verify_manifest("13B",RESULT/"micro/MICRO-ROBUSTNESS-PHASE13-BATTERY")
    verify_manifest("13C",RESULT/"hybrid/LTD-ROBUSTNESS-PHASE13-BATTERY")
    ctab=pd.read_csv(P15C/"P15C_components.csv")
    btab=pd.read_csv(P15B/"P15B_summary.csv")
    if len(ctab)!=30 or len(btab)!=24:raise RuntimeError("UNEXPECTED_SOURCE_SUMMARIES")
    cidx=ctab.set_index(["origin","window","candidate"])
    rows=[];bootrows=[];site_rows=[];day_rows=[];in_sha={}
    for oi,origin in enumerate(ORIGINS):
        macrofile=CACHE/"macro"/(origin+".npz")
        msha=sha(macrofile)
        meta=json.loads(macrofile.with_suffix(".json").read_text())
        if meta.get("identity")!={"origin":origin} or meta.get("outputs_sha256",{}).get("cache")!=msha:
            raise RuntimeError("MACRO_PROVENANCE_INVALID")
        in_sha[str(macrofile)]=msha
        with np.load(macrofile,allow_pickle=False) as z:
            mz={k:z[k].copy() for k in z.files}
        for wi,window in enumerate(WINDOWS):
            micro_probs=[];reference=None
            for seed in (11,42,73):
                path=CACHE/origin/"UNIFORM"/str(seed)/(window+".npz")
                data=read_npz(path,["pcap_uid","query_date","y_true","candidate_labels","probs",
                                    "origin","window","seed","temporal_mode"])
                if (str(data["origin"]),str(data["window"]),int(data["seed"]),str(data["temporal_mode"]))!=(origin,window,seed,"UNIFORM"):
                    raise RuntimeError("EXPERT_IDENTITY_MISMATCH")
                current=[data[k] for k in ("pcap_uid","query_date","y_true","candidate_labels")]
                if reference is None:reference=current
                elif not all(np.array_equal(x,v) for x,v in zip(current,reference)):
                    raise RuntimeError("MICRO_UID_DATE_LABEL_MISALIGNED")
                micro_probs.append(data["probs"])
                in_sha[str(path)]=sha(path)
            uid,dates,y,labels=reference
            if len(labels)!=NCLASS or len(np.unique(uid))!=len(uid) or y.min()<0 or y.max()>=NCLASS:
                raise RuntimeError("CANONICAL_COHORT_INVALID")
            for k,v in [(f"pcap_uid_{window}",uid),(f"dates_{window}",dates),
                        (f"y_{window}",y),("candidate_labels",labels)]:
                if not np.array_equal(mz[k],v):raise RuntimeError("MACRO_UID_DATE_LABEL_MISALIGNED")
            micro=geometric(micro_probs)
            m0=mz[f"M0_{window}"].astype(np.float64)
            m1=mz[f"M1_{window}"].astype(np.float64)
            def hybrid(m):
                h=np.exp(.45*np.log(np.clip(micro,1e-12,1))+.55*np.log(np.clip(m,1e-12,1)))
                return h/h.sum(axis=1,keepdims=True)
            pairs={"Macro M1-M0":(m0,m1,"M0","M1"),
                   "Hybrid U3xM1-U3xM0":(hybrid(m0),hybrid(m1),"U3xM0","U3xM1")}
            for pi,(name,(old,new,oldkey,newkey)) in enumerate(pairs.items()):
                om=metric(old,y);nm=metric(new,y)
                for scores,key,now in [(om,oldkey,old),(nm,newkey,new)]:
                    prior=cidx.loc[(origin,window,key)]
                    for field in ("accuracy","macro_f1","top5_accuracy","mrr"):
                        if abs(scores[field]-float(prior[field]))>1e-5:
                            raise RuntimeError("P15C_SCORE_MISMATCH "+str((origin,window,key,field)))
                oldrank=ranks(old,y);newrank=ranks(new,y)
                gains=(oldrank!=1)&(newrank==1)
                harms=(oldrank==1)&(newrank!=1)
                r={"origin":origin,"window":window,"comparison":name,"n":len(y),
                   "rescued":int(gains.sum()),"harmed":int(harms.sum()),"net":int(gains.sum()-harms.sum())}
                for field in ("accuracy","macro_f1","top5_accuracy"):
                    r["delta_"+field]=float(nm[field]-om[field])
                if abs(r["delta_accuracy"]-r["net"]/len(y))>1e-9:
                    raise RuntimeError("PAIRED_ACCOUNTING_FAILURE")
                bs=bootstrap_paired(y,dates,old,new,int(conf["bootstrap"]["iterations"]),
                      int(conf["bootstrap"]["seed"])+oi*100+wi*10+pi)
                rows.append(r);bootrows.append({"origin":origin,"window":window,"comparison":name,**bs})
                df=pd.DataFrame({"date":dates.astype("datetime64[D]").astype(str),
                   "site":labels[y].astype(str),"gain":gains.astype(np.int64),
                   "harm":harms.astype(np.int64),"old_t5":(oldrank<=5).astype(np.int64),
                   "new_t5":(newrank<=5).astype(np.int64)})
                for column,dest in (("date",day_rows),("site",site_rows)):
                    for val,g in df.groupby(column,sort=True):
                        dest.append({"origin":origin,"window":window,"comparison":name,column:val,
                          "n":len(g),"rescued":int(g.gain.sum()),"harmed":int(g.harm.sum()),
                          "net":int(g.gain.sum()-g.harm.sum()),
                          "old_top5_count":int(g.old_t5.sum()),"new_top5_count":int(g.new_t5.sum())})
                print("P15D_PAIR_OK",origin,window,name,"gain",r["rescued"],"harm",r["harmed"],
                      "delta_f1",f"{r['delta_macro_f1']:+.6f}",
                      "ci95",f"[{bs['macro_f1_ci_low']:+.5f},{bs['macro_f1_ci_high']:+.5f}]")
    tab=pd.DataFrame(rows);boots=pd.DataFrame(bootrows);site=pd.DataFrame(site_rows);day=pd.DataFrame(day_rows)
    if len(tab)!=len(boots)!=12:raise RuntimeError("EXPECTED_12_PAIRS")
    if len(tab)!=12 or len(boots)!=12:raise RuntimeError("EXPECTED_12_PAIRS")
    for key,g in tab.groupby(["origin","window","comparison"]):
        ss=site.loc[(site.origin==key[0])&(site.window==key[1])&(site.comparison==key[2])]
        dd=day.loc[(day.origin==key[0])&(day.window==key[1])&(day.comparison==key[2])]
        for src in (ss,dd):
            if int(src.n.sum())!=int(g.iloc[0].n) or int(src.rescued.sum())!=int(g.iloc[0].rescued) or int(src.harmed.sum())!=int(g.iloc[0].harmed):
                raise RuntimeError("SITE_DAY_RECONCILIATION_FAILED "+str(key))
    report=produce_milestone(tab,boots,ctab,btab,site,{})
    OUT.mkdir(parents=True)
    outputs={"P15D_pairs.csv":tab,"P15D_day_bootstrap.csv":boots,
       "P15D_site_counts.csv":site,"P15D_day_counts.csv":day}
    hashes={}
    for name,frame in outputs.items():
        path=OUT/name;frame.to_csv(path,index=False);hashes[name]=sha(path)
    milestone=OUT/"P15_MILESTONE_AUTOGENERATED.md"
    milestone.write_text(report,encoding="utf-8");hashes[milestone.name]=sha(milestone)
    provenance={"stage":"P15D_HIST_PAIRED_M0_M1","status":"POSTHOC_DESCRIPTIVE",
      "independent_confirmation":False,"promotion_allowed":False,
      "future_b_opened":False,"dataset_c_opened":False,"training_allowed":False,
      "config_sha256":sha(CONFIG),"script_sha256":sha(Path(__file__).resolve()),
      "input_sha256":in_sha,"prior_manifests_sha256":{
          "P15A":sha(P15A/"P15A_manifest.json"),"P15B":sha(P15B/"P15B_manifest.json"),
          "P15C":sha(P15C/"P15C_manifest.json")},
      "outputs_sha256":hashes,"comparisons":12}
    (OUT/"P15D_manifest.json").write_text(json.dumps(provenance,indent=2,sort_keys=True))
    print("P15D_COMPLETE 12/12; P15_MILESTONE_GENERATED",milestone)
    print("P15D_FAR_SUMMARY")
    print(tab[tab.window=="FAR"].to_string(index=False,float_format=lambda x:f"{x:+.6f}"))
    print("P15_MILESTONE_SHA256",hashes[milestone.name])
if __name__=="__main__":
    main()
